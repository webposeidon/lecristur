function pad2(n: number): string {
  return String(n).padStart(2, '0');
}

function buildGeneratedItinerary(days: number, title: string): ItineraryDay[] {
  const result: ItineraryDay[] = [];
  for (let d = 1; d <= days; d++) {
    if (d === 1) {
      result.push({
        dayNumber: 1,
        title: `Ziua 1 – Plecare din Chișinău și primele vizite (${title})`,
        activities: [
          { time: '06:00', text: 'Plecare din Chișinău cu autocar modern' },
          { time: '11:30', text: 'Vizitarea primelor obiective turistice de pe traseu' },
          { time: '14:00', text: 'Pauză de prânz la restaurant tradițional' },
          {
            time: '18:00',
            text:
              days === 1
                ? 'Îmbarcare și retur spre Chișinău'
                : 'Cazare la hotel 3★ și timp liber',
          },
        ],
      });
    } else if (d === days) {
      result.push({
        dayNumber: d,
        title: `Ziua ${d} – Vizite matinale și retur la Chișinău`,
        activities: [
          { time: '08:00', text: 'Mic dejun la hotel' },
          { time: '09:30', text: 'Tur ghidat și timp liber pentru suveniruri' },
          { time: '15:00', text: 'Plecare spre Chișinău' },
          { time: '22:00', text: 'Sosire în Chișinău (în funcție de trafic)' },
        ],
      });
    } else {
      result.push({
        dayNumber: d,
        title: `Ziua ${d} – Explorarea obiectivelor principale`,
        activities: [
          { time: '08:00', text: 'Mic dejun la hotel' },
          { time: '09:30', text: 'Vizite ghidate la principalele atracții ale regiunii' },
          { time: '13:30', text: 'Prânz și timp liber pentru fotografii' },
          { time: '19:00', text: 'Întoarcere la hotel și seară liberă' },
        ],
      });
    }
  }
  return result;
}

function generateAllTrips(): Trip[] {
  const generated: Trip[] = GENERATED_SPECS.map((spec, idx) => {
    const base = BASE_TRIPS[spec.baseIndex];
    const tripNumber = BASE_TRIPS.length + idx + 1;
    const endDayNov = spec.startDayNov + Math.max(0, spec.days - 1);
    const endDayDec = spec.startDayDec + Math.max(0, spec.days - 1);

    const departures: Departure[] = [
      {
        id: `dep-${spec.slug}-2026-11-${pad2(spec.startDayNov)}`,
        startDate: `2026-11-${pad2(spec.startDayNov)}`,
        endDate: `2026-11-${pad2(endDayNov)}`,
        price: spec.price,
        totalSeats: 40,
        availableSeats: spec.seatsNov,
      },
      {
        id: `dep-${spec.slug}-2026-12-${pad2(spec.startDayDec)}`,
        startDate: `2026-12-${pad2(spec.startDayDec)}`,
        endDate: `2026-12-${pad2(endDayDec)}`,
        price: spec.price + 10,
        totalSeats: 40,
        availableSeats: spec.seatsDec,
      },
    ];

    const ratingValues = [4.6, 4.7, 4.8, 4.9];
    const rating = ratingValues[idx % ratingValues.length];
    const reviewCount = 38 + ((idx * 11) % 75);

    return {
      id: `trip-${tripNumber}`,
      slug: spec.slug,
      title: spec.title,
      subtitle: spec.subtitle,
      description: base.description,
      destinations: spec.destinations,
      badge: spec.badge,
      type: spec.type,
      days: spec.days,
      nights: spec.nights,
      transportIncluded: true,
      hotelStars: spec.days === 1 ? 0 : 3,
      rating,
      reviewCount,
      popularity: 88 - idx, // sub cele 12 modele de bază (100..89)
      images: [...base.images],
      highlights: [...base.highlights],
      included:
        spec.days === 1 ? COMMON_INCLUDED_ONEDAY : COMMON_INCLUDED_MULTIDAY,
      notIncluded: COMMON_NOT_INCLUDED,
      route: { ...base.route },
      itinerary: buildGeneratedItinerary(spec.days, spec.title),
      reviews: base.reviews.length > 0 ? [...base.reviews] : [],
      departures,
    };
  });

  return [...BASE_TRIPS, ...generated];
}

